from __future__ import annotations

import os
from pathlib import Path

import pytest

from src.validation import validate_artifacts


def test_required_artifacts_when_release_gate_requests_them() -> None:
    project = Path(__file__).resolve().parents[1]
    if os.environ.get("HW02_REQUIRE_ARTIFACTS") != "1" and not (project / "results" / "environment.json").exists():
        pytest.skip("artifacts are generated by the completed notebook")
    summary = validate_artifacts(project)
    assert summary["json_files"] == 4
    assert summary["csv_files"] == 9
    assert summary["figures"] == 5
