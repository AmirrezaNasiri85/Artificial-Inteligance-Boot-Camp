from __future__ import annotations

import os
from pathlib import Path

import pytest

from src.validation import validate_artifacts


def test_required_artifacts_when_release_gate_requests_them():
    project = Path(__file__).resolve().parents[1]
    if not (project / "src").is_dir():
        project = Path(__file__).resolve().parents[2]
    if (
        os.environ.get("HW03_REQUIRE_ARTIFACTS") != "1"
        and not (project / "results/environment.json").exists()
    ):
        pytest.skip("artifacts are generated by the completed notebook")
    s = validate_artifacts(project)
    assert (s["json_files"], s["csv_files"], s["figures"], s["artifact_count"]) == (3, 10, 5, 18)
